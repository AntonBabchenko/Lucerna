#!/usr/bin/env node
// Generates src/lib/i18n/keys.generated.ts — a union of every dot-path
// key in en.json (the source-of-truth dictionary). Run with `--check`
// to fail CI when the committed file is stale.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const EN = resolve('src/lib/i18n/locales/en.json');
const OUT = resolve('src/lib/i18n/keys.generated.ts');

function flatten(obj, prefix = '') {
  const keys = [];
  for (const [k, v] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      keys.push(...flatten(v, path));
    } else {
      keys.push(path);
    }
  }
  return keys;
}

const dict = JSON.parse(readFileSync(EN, 'utf8'));
const keys = flatten(dict).sort();
const body = keys.map((k) => `  | '${k}'`).join('\n');
const content =
  `// GENERATED by tools/gen-i18n-keys.mjs — do not edit by hand.\n` +
  `// Run \`pnpm i18n:keys\` after changing en.json.\n` +
  `export type TranslationKey =\n${body};\n`;

if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(OUT, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== content) {
    console.error('[i18n] keys.generated.ts is stale. Run `pnpm i18n:keys`.');
    process.exit(1);
  }
  console.log('[i18n] keys.generated.ts is up to date.');
} else {
  writeFileSync(OUT, content, 'utf8');
  console.log(`[i18n] wrote ${keys.length} keys to keys.generated.ts`);
}
