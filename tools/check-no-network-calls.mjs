#!/usr/bin/env node
// Fails CI if direct network APIs appear in shipped webview code.
// All outbound HTTP must go through Rust's network:: module
// (see docs/PRINCIPLES.md Part A item 2 and Part B item 4).
//
// Scope: the SvelteKit source (`src/`), the static assets served verbatim
// at the webview root (`static/` — e.g. theme-init.js), and the HTML shell
// (`.html`). Anything that reaches the webview at runtime must be covered —
// a raw `fetch()` in static/theme-init.js or a `<script>` in app.html would
// bypass the chokepoint just as surely as one in src/.
//
// Threat model: this is a guardrail against accidental network code,
// not a sandbox. A determined developer can bypass it with dynamic
// constructions like `globalThis['fet' + 'ch']('url')`. The point is
// to make the principle hard to violate by mistake — anything that
// looks suspicious enough to write that way will not survive review.

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { extname, join, resolve } from 'node:path';

// Scan the SvelteKit source and the static asset dir (shipped verbatim to the
// webview). Missing roots are skipped so the gate doesn't crash on a checkout
// without one.
const ROOTS = [resolve('src'), resolve('static')].filter((p) => existsSync(p));
const ALLOWED = new Set([
  // Generated by tauri-specta — uses the official Tauri invoke channel
  // (not a direct network call). Excluded so regenerations stay clean.
  resolve('src/lib/ipc/bindings.ts'),
]);

const PATTERNS = [
  { name: 'fetch(', re: /\bfetch\s*\(/g },
  { name: 'XMLHttpRequest', re: /\bXMLHttpRequest\b/g },
  { name: 'new WebSocket(', re: /\bnew\s+WebSocket\s*\(/g },
  { name: 'navigator.sendBeacon', re: /\bnavigator\.sendBeacon\b/g },
  { name: 'EventSource', re: /\bnew\s+EventSource\s*\(/g },
];

const EXTS = new Set(['.ts', '.tsx', '.js', '.svelte', '.mjs', '.cjs', '.html']);

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const s = statSync(full);
    if (s.isDirectory()) {
      out.push(...walk(full));
    } else if (EXTS.has(extname(entry))) {
      out.push(full);
    }
  }
  return out;
}

let violations = 0;
const files = ROOTS.flatMap((root) => walk(root));
for (const file of files) {
  if (ALLOWED.has(file)) continue;
  const content = readFileSync(file, 'utf8');
  const lines = content.split('\n');
  for (const { name, re } of PATTERNS) {
    for (let i = 0; i < lines.length; i++) {
      re.lastIndex = 0;
      if (re.test(lines[i])) {
        console.error(`${file}:${i + 1}: forbidden network API "${name}"`);
        violations++;
      }
    }
  }
}

if (violations > 0) {
  console.error(
    `\n${violations} violation(s). All outbound HTTP must go through Rust (see docs/PRINCIPLES.md).`,
  );
  process.exit(1);
}
console.log('No forbidden network APIs found in src/ or static/.');
